// Filter out pre-baked duplicate derivative variants from base cannabinoids
// (e.g., 9h-hhc, 10-oh-hhc, thco-acetate are dynamically generated by variant dropdown)
const baseWeedFiltered = CANNABINOID_DATABASE.filter((c) => {
  const isPrebakedMod = /^(9h-|9-oh-|10-oh-|8-oh-|11-oh-|thco-|hhco-)/i.test(
    c.id
  );
  return !isPrebakedMod;
});

const rawCombined: CannabinoidProfile[] = [
  ...baseWeedFiltered,
  ...EXPANDED_SUBSTANCES_PART1,
  ...EXPANDED_SUBSTANCES_PART2,
  ...EXPANDED_SUBSTANCES_PART3,
  ...EXPANDED_SUBSTANCES_PART4,
  ...EXPANDED_SUBSTANCES_PART5,
  ...EXPANDED_SUBSTANCES_PART6,
];

// Deduplicate by ID
const map = new Map<string, CannabinoidProfile>();
for (const sub of rawCombined) {
  if (!map.has(sub.id)) {
    map.set(sub.id, sub);
  }
}

export const ALL_SUBSTANCES_DATABASE: CannabinoidProfile[] = Array.from(
  map.values()
);

export function getSubstanceById(id: string): CannabinoidProfile {
  const modMatch = id.match(
    /^(.+)-mod-(9h|9-oh|9oh|10-oh|10oh|8-oh|8oh|11-oh|11oh|oac|o-acetate)$/
  );
  if (modMatch) {
    const baseId = modMatch[1];
    const rawMod = modMatch[2];
    const base =
      ALL_SUBSTANCES_DATABASE.find((c) => c.id === baseId) ||
      ALL_SUBSTANCES_DATABASE[0];
    const normalizedMod: DerivativeModType =
      rawMod === '9oh'
        ? '9-oh'
        : rawMod === '10oh'
        ? '10-oh'
        : rawMod === '8oh'
        ? '8-oh'
        : rawMod === '11oh'
        ? '11-oh'
        : rawMod === 'oac'
        ? 'o-acetate'
        : (rawMod as DerivativeModType);
    return applyDerivativeModification(base, normalizedMod);
  }
  return (
    ALL_SUBSTANCES_DATABASE.find((c) => c.id === id) ||
    ALL_SUBSTANCES_DATABASE[0]
  );
}

export type WeedSubcategory = 'Natural' | 'Semisynthetic' | 'Synthetic';

export function getWeedSubcategory(item: CannabinoidProfile): WeedSubcategory {
  const cls = item.classification.toLowerCase();
  if (cls.includes('phytocannabinoid')) return 'Natural';
  if (cls.includes('semi-synthetic')) return 'Semisynthetic';
  return 'Synthetic';
}

export function getNormalizedMacroCategory(
  cls: string
): SubstanceMacroCategory {
  const lower = cls.toLowerCase();
  if (
    lower.includes('cannabinoid') ||
    lower.includes('phytocannabinoid') ||
    lower.includes('semi-synthetic') ||
    lower.includes('9h-') ||
    lower.includes('series')
  ) {
    return 'Weed & Cannabinoids';
  }

  // Prescription pharmaceuticals
  if (
    lower === 'benzodiazepine' ||
    lower === 'opioid analgesic' ||
    lower === 'gabapentinoid' ||
    lower === 'rx stimulant' ||
    lower.includes('barbiturate') ||
    lower.includes('quinazolinone') ||
    lower.includes('carbamate') ||
    lower.includes('sedative') ||
    lower.includes('phenidate') ||
    lower.includes('adamantane') ||
    lower.includes('anxiolytic')
  ) {
    return 'Prescription Pharmaceuticals';
  }

  // Everything else is Illicit / NPS / Botanicals
  return 'Illicit Substances';
}

