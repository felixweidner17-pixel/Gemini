export function getCannabinoidById(id: string): CannabinoidProfile {
  const modMatch = id.match(
    /^(.+)-mod-(9h|9-oh|9oh|10-oh|10oh|8-oh|8oh|11-oh|11oh|oac|o-acetate)$/
  );
  if (modMatch) {
    const baseId = modMatch[1];
    const rawMod = modMatch[2];
    const base =
      CANNABINOID_DATABASE.find((c) => c.id === baseId) ||
      CANNABINOID_DATABASE[0];
    const normalizedMod: DerivativeModType =
      rawMod === '9oh'
        ? '9-oh'
        : rawMod === '10oh'
        ? '10-oh'
        : rawMod === '8oh'
        ? '8-oh'
        : rawMod === '11oh'
        ? '11-oh'
        : rawMod === 'oac'
        ? 'o-acetate'
        : (rawMod as DerivativeModType);
    return applyDerivativeModification(base, normalizedMod);
  }
  return (
    CANNABINOID_DATABASE.find((c) => c.id === id) || CANNABINOID_DATABASE[0]
  );
}

